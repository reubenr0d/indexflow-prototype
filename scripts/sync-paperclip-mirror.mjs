#!/usr/bin/env node
/**
 * Generate the Paperclip-native mirror under `paperclip/companies/indexflow/`.
 *
 * Why this exists
 * ---------------
 * The `paperclip-agent-companies-plugin` v0.9.x classifier (see worker.js
 * `classifyCompanyContentPath`) requires this exact directory layout:
 *
 *   <source-root>/
 *     COMPANY.md
 *     agents/<slug>/AGENTS.md      (note: AGENTS.md, plural, capital S, inside a per-slug folder)
 *     skills/<slug>/SKILL.md       (skills at source-root, NOT under agents/)
 *     projects/<slug>/PROJECT.md
 *     tasks/<slug>/TASK.md
 *     issues/<slug>/ISSUE.md
 *
 * Our canonical layout is flat (`agents/<slug>.md` files) because
 * `scripts/agent-runner.mjs` reads them that way. Rather than restructure
 * the runtime, we mirror the canonical sources into the Paperclip-expected
 * shape and point the Paperclip "Repository Catalog" source at
 * `paperclip/companies/indexflow/` (NOT the repo root, to avoid the
 * recursive walker discovering two COMPANY.md files).
 *
 * The mirror is git-tracked so that:
 *   - GitHub-URL sources work (Paperclip shallow-clones and finds the mirror)
 *   - Local-path sources don't require running this script every time
 *
 * Run before committing changes to COMPANY.md or any mirrored agent prompt:
 *   npm run sync:paperclip
 *
 * Or wire it into a pre-commit hook.
 *
 * Active runnable employees only. Prompt-only employees
 * (risk-officer-self-improvement, risk-officer-self-improvement-issues)
 * are NOT mirrored — they're invoked inline by sibling scripts
 * (`scripts/run-self-improvement-risk-officer.mjs` etc.) and have no
 * heartbeat surface. They remain documented in COMPANY.md `employees:`.
 */
import { mkdir, readFile, writeFile, rm } from "node:fs/promises";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = join(SCRIPT_DIR, "..");
const MIRROR_ROOT = join(REPO_ROOT, "paperclip", "companies", "indexflow");

// envPassthrough lists mirror the COMPANY.md employees[].adapter.envPassthrough
// blocks. They feed `.paperclip.yaml` `inputs.env` so re-imports declare the
// required secrets to the operator; `scripts/paperclip-configure-adapters.mjs`
// then binds them to actual secret_refs at runtime.
const COMMON_REQUIRED_ENV = [
  "LLM_API_KEY",
  "LLM_BASE_URL",
  "LLM_MODEL",
  "GH_TOKEN",
  "AGENT_NETWORK",
  "AGENT_NON_INTERACTIVE_WRITE_EXECUTE",
  "AGENT_MAX_TURNS",
];

const ACTIVE_RUNNABLE_EMPLOYEES = [
  {
    slug: "self-improver-issues",
    sourcePath: "agents/self-improver-issues.md",
    requiredEnv: COMMON_REQUIRED_ENV,
    optionalEnv: ["LLM_MODEL_SELF_IMPROVER_ISSUES"],
  },
  {
    slug: "issue-implementer",
    sourcePath: "agents/issue-implementer.md",
    requiredEnv: COMMON_REQUIRED_ENV,
    optionalEnv: ["LLM_MODEL_ISSUE_IMPLEMENTER"],
  },
];

async function copyCompanyManifest() {
  const src = join(REPO_ROOT, "COMPANY.md");
  const dest = join(MIRROR_ROOT, "COMPANY.md");
  const content = await readFile(src, "utf8");
  await mkdir(dirname(dest), { recursive: true });
  await writeFile(dest, content, "utf8");
  return dest;
}

async function mirrorAgent({ slug, sourcePath }) {
  const src = join(REPO_ROOT, sourcePath);
  const destDir = join(MIRROR_ROOT, "agents", slug);
  const dest = join(destDir, "AGENTS.md");
  const content = await readFile(src, "utf8");
  await mkdir(destDir, { recursive: true });
  await writeFile(dest, content, "utf8");
  return dest;
}

// Build the Paperclip portable-extension sidecar (.paperclip.yaml). The
// `paperclip-agent-companies-plugin` v0.9.x importer reads `agents[<slug>]`
// for adapter type/config and `inputs.env` for declared env requirements
// (see @paperclipai/server/dist/services/company-portability.js → the
// `extension.agents` and `readAgentEnvInputs` paths).
//
// `cwd` is intentionally omitted because it's machine-specific; the
// `scripts/paperclip-configure-adapters.mjs` script fills it post-import and
// also wires `env` to actual secret_refs in the host secrets store.
function buildPaperclipExtensionYaml() {
  const lines = ["# Generated by scripts/sync-paperclip-mirror.mjs — do not edit by hand.", "agents:"];
  for (const employee of ACTIVE_RUNNABLE_EMPLOYEES) {
    lines.push(`  ${employee.slug}:`);
    lines.push(`    adapter:`);
    lines.push(`      type: process`);
    lines.push(`      config:`);
    lines.push(`        command: npm`);
    const argsJson = JSON.stringify(["run", "agent:run", "--", employee.slug]);
    lines.push(`        args: ${argsJson}`);
    lines.push(`    inputs:`);
    lines.push(`      env:`);
    for (const key of employee.requiredEnv) {
      lines.push(`        ${key}:`);
      lines.push(`          kind: secret`);
      lines.push(`          requirement: required`);
    }
    for (const key of employee.optionalEnv) {
      lines.push(`        ${key}:`);
      lines.push(`          kind: secret`);
      lines.push(`          requirement: optional`);
    }
  }
  return `${lines.join("\n")}\n`;
}

async function writePaperclipExtension() {
  const dest = join(MIRROR_ROOT, ".paperclip.yaml");
  await writeFile(dest, buildPaperclipExtensionYaml(), "utf8");
  return dest;
}

async function main() {
  await rm(MIRROR_ROOT, { recursive: true, force: true });
  await mkdir(MIRROR_ROOT, { recursive: true });

  const written = [];
  written.push(await copyCompanyManifest());
  written.push(await writePaperclipExtension());
  for (const employee of ACTIVE_RUNNABLE_EMPLOYEES) {
    written.push(await mirrorAgent(employee));
  }

  const relativeMirror = MIRROR_ROOT.replace(`${REPO_ROOT}/`, "");
  console.log(`Mirrored ${written.length} files into ${relativeMirror}/:`);
  for (const path of written) {
    console.log(`  - ${path.replace(`${REPO_ROOT}/`, "")}`);
  }
  console.log("");
  console.log(`Point Paperclip's Repository Catalog source at:`);
  console.log(`  ${MIRROR_ROOT}`);
}

main().catch((error) => {
  console.error(`sync-paperclip-mirror failed: ${error.message}`);
  process.exitCode = 1;
});
